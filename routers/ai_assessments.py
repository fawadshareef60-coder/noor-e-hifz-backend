from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from typing import List, Optional
from app.database import get_db
from app.models_ai import AIAssessment, MistakeRecord
from app.schemas import AIAssessmentResponse, MistakeRecordSchema
from app.auth import get_current_user
from app.ai_engine import ai_speech_engine

router = APIRouter(
    prefix="/assessments",
    tags=["AI Evaluation Engine"]
)

# ==========================================
# 1. LIVE TRIGGER RECITATION AI AUDIT PIPELINE
# ==========================================
@router.post("/analyze-recitation", status_code=status.HTTP_201_CREATED)
def trigger_audio_recitation_ai_analysis(
    recording_id: str,
    surah_number: int,
    ayah_number: int,
    audio_format: str,
    db: Session = Depends(get_db),
    current_user: dict = Depends(get_current_user)
):
    """
    Student ki live audio submission par automatic AI evaluation engine trigger karta hai 
    aur granular mistakes aur analytics report database mein generate karta hai.
    """
    # Trigger processing inside advanced speech analytics wrapper
    ai_result = ai_speech_engine.process_recitation_audio(
        db=db,
        recording_id=recording_id,
        student_id=current_user["id"],
        target_surah=surah_number,
        target_ayah=ayah_number,
        audio_file_format=audio_format
    )

    if not ai_result["success"]:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=ai_result["error"]
        )

    # Insert overview assessment records into postgres
    new_assessment = AIAssessment(
        recording_id=ai_result["recording_id"],
        student_id=ai_result["student_id"],
        recognized_transcript=ai_result["recognized_transcript"],
        confidence_level=ai_result["confidence_level"],
        is_low_confidence=ai_result["is_low_confidence"]
    )
    db.add(new_assessment)
    db.commit()
    db.refresh(new_assessment)

    # Insert individual error records generated by core AI engine model
    for mistake in ai_result["mistakes"]:
        new_mistake = MistakeRecord(
            assessment_id=new_assessment.id,
            ayah_id=mistake["ayah_id"],
            error_type=mistake["error_type"],
            word_index=mistake["word_index"],
            detected_mistake=mistake["detected_mistake"],
            suggested_correction=mistake["suggested_correction"],
            audio_timestamp_start=mistake["audio_timestamp_start"],
            audio_timestamp_end=mistake["audio_timestamp_end"]
        )
        db.add(new_mistake)
    
    db.commit()
    return {
        "status": "Success",
        "message": "AI model assessment aur mistakes analytics securely log ho gaye hain.",
        "assessment_id": str(new_assessment.id),
        "confidence_score": f"{ai_result['confidence_level']}%"
    }

# ==========================================
# 2. FETCH STUDENT REPORT BY RECORDING ID
# ==========================================
@router.get("/report/{recording_id}", response_model=AIAssessmentResponse)
def get_ai_report_by_recording(
    recording_id: str, 
    db: Session = Depends(get_db), 
    current_user: dict = Depends(get_current_user)
):
    """
    Student ya Teacher ke dashboard ke liye specific recording ka granular AI fault analysis fetch karta hai.
    """
    assessment = db.query(AIAssessment).filter(AIAssessment.recording_id == recording_id).first()
    if not assessment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, 
            detail="Is recording ka AI analysis report abhi tak generate nahi hua."
        )

    # Security check: User can only see their own reports unless admin
    if assessment.student_id != current_user["id"] and current_user["role"] != "administrator":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN, 
            detail="Aapko is evaluation audit sheet ko dekhne ki ijazat nahi hai."
        )

    return assessment
